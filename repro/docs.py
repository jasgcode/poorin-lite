"""The project's docs: decisions, experiments, and designs, each with a YAML header, and the index
generated from those headers.

    uv run python -m repro.docs            # rewrite docs/index.md
    uv run python -m repro.docs --check    # fail on an invalid header or a stale index

``docs/README.md`` holds the rules agents and people follow. This module checks the part a program
can: each file's name and header. The launcher reads an experiment's status here to refuse
``--experiment`` for a missing or closed experiment.
"""

import datetime
import re
from collections import Counter
from dataclasses import dataclass
from enum import StrEnum
from pathlib import Path
from typing import Any

import click
import yaml

DOCS_DIR = "docs"
INDEX_FILENAME = "index.md"
HEADER_DELIMITER = "---"
MAX_SUMMARY_LENGTH = 120
INDEX_BANNER = "<!-- Generated by `python -m repro.docs`. Do not edit. -->"
EMPTY_SECTION = "None."

_SLUG = r"[a-z0-9][a-z0-9-]*"
ADOPTED = "adopted"
SUPERSEDED = "superseded"
OPEN = "open"
CLOSED = "closed"


class Kind(StrEnum):
    DECISION = "decision"
    EXPERIMENT = "experiment"
    DESIGN = "design"


@dataclass(frozen=True)
class KindRules:
    directory: str
    file_name: re.Pattern[str]
    """Its groups: the name the index shows."""
    statuses: tuple[str, ...]
    """Empty for a kind with no ``status`` field."""


RULES = {
    Kind.DECISION: KindRules("decisions", re.compile(rf"^(\d{{4}})-{_SLUG}\.md$"), (ADOPTED, SUPERSEDED)),
    Kind.EXPERIMENT: KindRules("experiments", re.compile(rf"^({_SLUG})\.md$"), (OPEN, CLOSED)),
    Kind.DESIGN: KindRules("designs", re.compile(rf"^\d{{4}}-\d{{2}}-\d{{2}}-({_SLUG})\.md$"), ()),
}
# The order of kinds on one date in the timeline.
KIND_ORDER = tuple(Kind)


class DocError(ValueError):
    """A doc whose name or header breaks the rules; the message names each file."""


@dataclass(frozen=True)
class Doc:
    kind: Kind
    path: str
    """Relative to the docs directory, with ``/`` separators."""
    name: str
    """What the index shows: a decision's number, an experiment's slug, a design's slug."""
    date: datetime.date
    status: str | None
    summary: str


def _header(text: str) -> dict[str, Any] | None:
    lines = text.splitlines()
    if not lines or lines[0] != HEADER_DELIMITER or HEADER_DELIMITER not in lines[1:]:
        return None
    end = lines.index(HEADER_DELIMITER, 1)
    loaded = yaml.safe_load("\n".join(lines[1:end]))
    return loaded if isinstance(loaded, dict) else None


def _problems(kind: Kind, header: dict[str, Any]) -> list[str]:
    rules = RULES[kind]
    expected = {"date", "summary"} | ({"status"} if rules.statuses else set())
    problems = [f"missing field {name!r}" for name in sorted(expected - header.keys())]
    problems += [f"unknown field {name!r}" for name in sorted(header.keys() - expected)]
    if "date" in header and not isinstance(header["date"], datetime.date):
        problems.append(f"date {header['date']!r} is not YYYY-MM-DD")
    if "status" in header and rules.statuses and header["status"] not in rules.statuses:
        problems.append(f"status {header['status']!r} is not one of {', '.join(rules.statuses)}")
    summary = header.get("summary")
    if "summary" in header and (not isinstance(summary, str) or not summary.strip() or "\n" in summary.strip()):
        problems.append("summary must be one line of text")
    elif isinstance(summary, str) and len(summary) > MAX_SUMMARY_LENGTH:
        problems.append(f"summary is {len(summary)} characters; the limit is {MAX_SUMMARY_LENGTH}")
    return problems


def _read(docs_dir: Path, kind: Kind, path: Path) -> tuple[Doc | None, list[str]]:
    relative = path.relative_to(docs_dir).as_posix()
    match = RULES[kind].file_name.match(path.name)
    if match is None:
        return None, [f"{relative}: file name does not follow {RULES[kind].file_name.pattern}"]
    header = _header(path.read_text())
    if header is None:
        return None, [f"{relative}: no header; the file must start with a --- delimited YAML header"]
    problems = _problems(kind, header)
    if problems:
        return None, [f"{relative}: {problem}" for problem in problems]
    doc = Doc(kind, relative, match.group(1), header["date"], header.get("status"), header["summary"].strip())
    return doc, []


def read_docs(docs_dir: Path) -> list[Doc]:
    """Every decision, experiment, and design under ``docs_dir``.

    Raises:
        DocError: A file name or header breaks the rules, or two decisions share a number. The
            message lists every problem found.
    """
    docs: list[Doc] = []
    problems: list[str] = []
    for kind in Kind:
        directory = docs_dir / RULES[kind].directory
        for path in sorted(directory.glob("*.md")):
            doc, found = _read(docs_dir, kind, path)
            problems += found
            if doc is not None:
                docs.append(doc)
    numbers = Counter(doc.name for doc in docs if doc.kind is Kind.DECISION)
    problems += [f"decisions: number {number} is used {count} times" for number, count in numbers.items() if count > 1]
    if problems:
        raise DocError("\n".join(problems))
    return docs


def experiment_status(docs_dir: Path, slug: str) -> str:
    """The status in ``docs_dir/experiments/{slug}.md``'s header.

    Raises:
        FileNotFoundError: No such experiment.
        DocError: ``slug`` is not a slug, or the file's header breaks the rules.
    """
    if RULES[Kind.EXPERIMENT].file_name.match(f"{slug}.md") is None:
        raise DocError(f"{slug!r} is not a slug: lowercase letters, digits, and hyphens")
    path = docs_dir / RULES[Kind.EXPERIMENT].directory / f"{slug}.md"
    if not path.is_file():
        raise FileNotFoundError(path)
    doc, problems = _read(docs_dir, Kind.EXPERIMENT, path)
    if doc is None:
        raise DocError("\n".join(problems))
    assert doc.status is not None
    return doc.status


def _link(doc: Doc) -> str:
    return f"[{doc.name}]({doc.path})"


def render_index(docs: list[Doc]) -> str:
    """``docs/index.md``: the open experiments, then every doc newest first."""
    open_experiments = sorted(
        (doc for doc in docs if doc.kind is Kind.EXPERIMENT and doc.status == OPEN), key=lambda doc: doc.path
    )
    timeline = sorted(docs, key=lambda doc: (-doc.date.toordinal(), KIND_ORDER.index(doc.kind), doc.path))
    lines = [INDEX_BANNER, "# Docs index", "", "## Open experiments", ""]
    lines += [f"- {_link(doc)} ({doc.date.isoformat()}): {doc.summary}" for doc in open_experiments] or [EMPTY_SECTION]
    lines += ["", "## Timeline", ""]
    if timeline:
        lines += ["| Date | Kind | Document | Summary |", "|---|---|---|---|"]
        for doc in timeline:
            summary = f"({SUPERSEDED}) {doc.summary}" if doc.status == SUPERSEDED else doc.summary
            lines.append(f"| {doc.date.isoformat()} | {doc.kind} | {_link(doc)} | {summary.replace('|', '\\|')} |")
    else:
        lines.append(EMPTY_SECTION)
    return "\n".join(lines) + "\n"


@click.command()
@click.option("--check", is_flag=True, help="Write nothing; fail on an invalid header or a stale index.")
@click.option(
    "--docs",
    "docs_dir",
    type=click.Path(file_okay=False, path_type=Path),
    default=Path(DOCS_DIR),
    show_default=True,
    help="The docs directory.",
)
def main(check: bool, docs_dir: Path) -> None:
    """Rewrite the docs index from the headers of every decision, experiment, and design."""
    try:
        index = render_index(read_docs(docs_dir))
    except DocError as e:
        raise click.ClickException(str(e)) from e
    path = docs_dir / INDEX_FILENAME
    if not check:
        path.write_text(index)
        return
    if not path.is_file() or path.read_text() != index:
        raise click.ClickException(f"{path} is stale. Run: uv run python -m repro.docs")


if __name__ == "__main__":
    main()
