"""The project docs: header validation and the generated index (repro.docs)."""

from pathlib import Path

import pytest
from click.testing import CliRunner

from repro.docs import DocError, experiment_status, main, read_docs, render_index

REPO_DOCS = Path(__file__).resolve().parents[1] / "docs"


def _doc(docs: Path, relative: str, header: str, body: str = "") -> None:
    path = docs / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f"---\n{header.strip()}\n---\n\n{body}")


@pytest.fixture
def docs(tmp_path) -> Path:
    path = tmp_path / "docs"
    for kind in ("decisions", "experiments", "designs"):
        (path / kind).mkdir(parents=True)
        (path / kind / ".gitkeep").write_text("")
    return path


def _full(docs: Path) -> None:
    _doc(docs, "decisions/0001-adam.md", "date: 2026-10-15\nstatus: superseded\nsummary: Adam is the default")
    _doc(docs, "decisions/0002-muon.md", "date: 2026-10-18\nstatus: adopted\nsummary: Muon is the default")
    _doc(docs, "experiments/muon-vs-adam.md", "date: 2026-10-17\nstatus: closed\nsummary: Muon wins by 0.04")
    _doc(docs, "experiments/warmup.md", "date: 2026-10-18\nstatus: open\nsummary: Does warmup help Muon?")
    _doc(docs, "designs/2026-10-16-optimizers-design.md", "date: 2026-10-16\nsummary: Pluggable optimizers")


def test_the_index_lists_open_experiments_and_every_doc_newest_first(docs):
    _full(docs)
    assert render_index(read_docs(docs)) == (
        "<!-- Generated by `python -m repro.docs`. Do not edit. -->\n"
        "# Docs index\n"
        "\n"
        "## Open experiments\n"
        "\n"
        "- [warmup](experiments/warmup.md) (2026-10-18): Does warmup help Muon?\n"
        "\n"
        "## Timeline\n"
        "\n"
        "| Date | Kind | Document | Summary |\n"
        "|---|---|---|---|\n"
        # Same date: decision before experiment.
        "| 2026-10-18 | decision | [0002](decisions/0002-muon.md) | Muon is the default |\n"
        "| 2026-10-18 | experiment | [warmup](experiments/warmup.md) | Does warmup help Muon? |\n"
        "| 2026-10-17 | experiment | [muon-vs-adam](experiments/muon-vs-adam.md) | Muon wins by 0.04 |\n"
        "| 2026-10-16 | design | [optimizers-design](designs/2026-10-16-optimizers-design.md) "
        "| Pluggable optimizers |\n"
        "| 2026-10-15 | decision | [0001](decisions/0001-adam.md) | (superseded) Adam is the default |\n"
    )


def test_an_empty_docs_directory_indexes_to_empty_sections(docs):
    index = render_index(read_docs(docs))
    assert index.endswith("## Open experiments\n\nNone.\n\n## Timeline\n\nNone.\n")


@pytest.mark.parametrize(
    ("relative", "header", "problem"),
    [
        ("decisions/0001-x.md", "status: adopted\nsummary: s", "date"),
        ("decisions/0001-x.md", "date: 2026-10-17\nsummary: s", "status"),
        ("decisions/0001-x.md", "date: 2026-10-17\nstatus: open\nsummary: s", "status"),
        ("experiments/x.md", "date: 2026-10-17\nstatus: adopted\nsummary: s", "status"),
        ("designs/2026-10-17-x.md", "date: 2026-10-17\nstatus: open\nsummary: s", "status"),
        ("experiments/x.md", "date: 2026-10-17\nstatus: open\nsummary: s\nruns: []", "runs"),
        ("experiments/x.md", "date: 17 October\nstatus: open\nsummary: s", "date"),
        ("experiments/x.md", "date: 2026-10-17\nstatus: open\nsummary: " + "s" * 121, "summary"),
        ("experiments/x.md", "date: 2026-10-17\nstatus: open\nsummary: |\n  two\n  lines", "summary"),
        ("experiments/Muon_vs_Adam.md", "date: 2026-10-17\nstatus: open\nsummary: s", "file name"),
        ("decisions/1-x.md", "date: 2026-10-17\nstatus: adopted\nsummary: s", "file name"),
        ("designs/x.md", "date: 2026-10-17\nsummary: s", "file name"),
    ],
)
def test_an_invalid_header_names_the_file_and_the_problem(docs, relative, header, problem):
    _doc(docs, relative, header)
    with pytest.raises(DocError, match=problem) as raised:
        read_docs(docs)
    assert relative in str(raised.value)


def test_a_file_without_a_header_is_rejected(docs):
    (docs / "experiments" / "x.md").write_text("# Just a title\n")
    with pytest.raises(DocError, match=r"experiments/x\.md: no header"):
        read_docs(docs)


def test_two_decisions_with_one_number_are_rejected(docs):
    _doc(docs, "decisions/0001-a.md", "date: 2026-10-17\nstatus: adopted\nsummary: a")
    _doc(docs, "decisions/0001-b.md", "date: 2026-10-17\nstatus: adopted\nsummary: b")
    with pytest.raises(DocError, match="0001"):
        read_docs(docs)


def test_every_invalid_file_is_reported_at_once(docs):
    _doc(docs, "experiments/a.md", "date: 2026-10-17\nsummary: s")
    _doc(docs, "experiments/b.md", "date: 2026-10-17\nsummary: s")
    with pytest.raises(DocError) as raised:
        read_docs(docs)
    assert "experiments/a.md" in str(raised.value) and "experiments/b.md" in str(raised.value)


def test_main_writes_the_index_and_check_passes_on_it(docs):
    _full(docs)
    written = CliRunner().invoke(main, ["--docs", str(docs)])
    assert written.exit_code == 0, written.output
    assert (docs / "index.md").read_text() == render_index(read_docs(docs))
    checked = CliRunner().invoke(main, ["--docs", str(docs), "--check"])
    assert checked.exit_code == 0, checked.output


def test_check_fails_on_a_stale_index_and_writes_nothing(docs):
    _full(docs)
    CliRunner().invoke(main, ["--docs", str(docs)])
    _doc(docs, "experiments/new.md", "date: 2026-10-19\nstatus: open\nsummary: A new question")
    before = (docs / "index.md").read_text()
    checked = CliRunner().invoke(main, ["--docs", str(docs), "--check"])
    assert checked.exit_code != 0
    assert "python -m repro.docs" in checked.output
    assert (docs / "index.md").read_text() == before


def test_check_fails_on_an_invalid_header(docs):
    _doc(docs, "experiments/x.md", "date: 2026-10-17\nsummary: s")
    checked = CliRunner().invoke(main, ["--docs", str(docs), "--check"])
    assert checked.exit_code != 0
    assert "experiments/x.md" in checked.output


def test_experiment_status_reads_the_experiments_header(docs):
    _doc(docs, "experiments/warmup.md", "date: 2026-10-18\nstatus: open\nsummary: Does warmup help?")
    assert experiment_status(docs, "warmup") == "open"
    with pytest.raises(FileNotFoundError):
        experiment_status(docs, "missing")


def test_the_repositorys_own_index_is_current():
    checked = CliRunner().invoke(main, ["--docs", str(REPO_DOCS), "--check"])
    assert checked.exit_code == 0, checked.output


def test_experiment_status_refuses_a_slug_that_leaves_the_experiments_directory(docs):
    _doc(docs, "decisions/0001-x.md", "date: 2026-10-17\nstatus: adopted\nsummary: s")
    with pytest.raises(DocError, match="not a slug"):
        experiment_status(docs, "../decisions/0001-x")
